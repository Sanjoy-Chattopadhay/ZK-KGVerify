def _save(fig, out: Path, stem: str) -> None:
    """Write every figure twice.

    Elsevier prefers vector artwork for line drawings, and a PDF scales to any
    column width without resampling. The PNG is kept for quick viewing and for
    anyone compiling with a toolchain that dislikes PDF includes.
    """
    fig.savefig(out / f"{stem}.pdf", bbox_inches="tight")
    fig.savefig(out / f"{stem}.png", bbox_inches="tight")
    plt.close(fig)
    print(f"  -> {stem}.pdf + {stem}.png")


def fig_training_curves(state: dict, out: Path) -> None:
    lp = state.get("link_prediction") or {}
    if not lp:
        return
    datasets = list(lp)
    fig, axes = plt.subplots(1, len(datasets), figsize=(5.5 * len(datasets), 3.4),
                             squeeze=False)
    for ax, ds in zip(axes[0], datasets):
        for i, (model, entry) in enumerate(lp[ds].items()):
            loss = (entry.get("history") or {}).get("loss") or []
            if loss:
                ax.plot(range(1, len(loss) + 1), loss,
                        label=model, color=PALETTE[i % len(PALETTE)], lw=1.5)
        ax.set_title(ds)
        ax.set_xlabel("Epoch")
        ax.set_ylabel("Training loss")
        ax.legend(frameon=False)
    fig.tight_layout()
    _save(fig, out, "training_curves")


def fig_metrics_comparison(state: dict, out: Path) -> None:
    lp = state.get("link_prediction") or {}
    if not lp:
        return
    metrics = ["MRR", "Hits@1", "Hits@3", "Hits@10"]
    datasets = list(lp)
    fig, axes = plt.subplots(1, len(datasets), figsize=(5.5 * len(datasets), 3.4),
                             squeeze=False)
    for ax, ds in zip(axes[0], datasets):
        models = list(lp[ds])
        width = 0.8 / max(len(models), 1)
        xs = range(len(metrics))
        for i, model in enumerate(models):
            vals = [lp[ds][model]["metrics"].get(m, 0.0) for m in metrics]
            ax.bar([x + i * width for x in xs], vals, width,
                   label=model, color=PALETTE[i % len(PALETTE)])
        ax.set_xticks([x + 0.4 - width / 2 for x in xs])
        ax.set_xticklabels(metrics)
        ax.set_ylabel("Score")
        ax.set_title(ds)
        ax.legend(frameon=False)
    fig.tight_layout()
    _save(fig, out, "metrics_comparison")


def fig_zkp_overhead(state: dict, out: Path) -> None:
    z = state.get("zkp")
    if not z:
        return
    gen = [t * 1000 for t in z.get("gen_times", [])]
    ver = [t * 1000 for t in z.get("verify_times", [])]
    if not gen or not ver:
        return

    fig, axes = plt.subplots(1, 3, figsize=(11, 3.2))
    axes[0].hist(gen, bins=40, color=PALETTE[0], edgecolor="white", lw=0.4)
    axes[0].axvline(statistics.fmean(gen), color=PALETTE[1], ls="--", lw=1.4,
                    label=f"mean {statistics.fmean(gen):.1f} ms")
    axes[0].set_xlabel("Proof generation (ms)")
    axes[0].set_ylabel("Count")
    axes[0].legend(frameon=False)

    axes[1].hist(ver, bins=40, color=PALETTE[2], edgecolor="white", lw=0.4)
    axes[1].axvline(statistics.fmean(ver), color=PALETTE[1], ls="--", lw=1.4,
                    label=f"mean {statistics.fmean(ver):.1f} ms")
    axes[1].set_xlabel("Proof verification (ms)")
    axes[1].legend(frameon=False)

    size = z.get("avg_proof_size_bytes", 0)
    axes[2].bar(["Proof"], [size], color=PALETTE[3], width=0.45)
    axes[2].set_ylabel("Bytes")
    axes[2].set_title(f"Wire size: {size:.0f} B")
    axes[2].grid(axis="x", visible=False)

    fig.tight_layout()
    _save(fig, out, "zkp_overhead")


def fig_gas_comparison(state: dict, out: Path) -> None:
    """V1 blind logging vs V2 chain-enforced verification."""
    t = state.get("onchain_verifier_test")
    if not t:
        return
    v1 = t["v1"]["log_gas_steady_mean"]
    v2 = t["v2"]["log_gas_steady_mean"]
    verify = t["v2"]["verify_gas_mean"]

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.2))
    bars = axes[0].bar(
        ["V1\nlog only\n(trusts caller)", "V2\nverify + log\n(chain-enforced)"],
        [v1, v2], color=[PALETTE[4], PALETTE[0]], width=0.5,
    )
    for b, v in zip(bars, [v1, v2]):
        axes[0].text(b.get_x() + b.get_width() / 2, v * 1.01, f"{v:,.0f}",
                     ha="center", fontsize=8)
    axes[0].set_ylabel("Gas per record")
    axes[0].set_title(f"Cost of trustlessness: +{v2 - v1:,.0f} gas "
                      f"({(v2 - v1) / v1 * 100:+.1f}%)")

    sep = state.get("sepolia") or {}
    if sep.get("num_tx"):
        gas = [x for x in [sep.get("first_tx_gas"), sep.get("steady_state_avg_gas")]]
        axes[1].bar(["First record\n(cold slots)", "Steady state"], gas,
                    color=[PALETTE[1], PALETTE[2]], width=0.5)
        for i, v in enumerate(gas):
            axes[1].text(i, v * 1.01, f"{v:,.0f}", ha="center", fontsize=8)
        axes[1].set_title(f"Measured on Sepolia ({sep['num_tx']} records)")
    else:
        axes[1].bar(["verifyProof\n(crypto only)", "verifyAndLog\n(with storage)"],
                    [verify, v2], color=[PALETTE[3], PALETTE[0]], width=0.5)
        axes[1].set_title("In-memory EVM breakdown")
    axes[1].set_ylabel("Gas")

    fig.tight_layout()
    _save(fig, out, "gas_comparison")


def fig_pipeline_timing(state: dict, out: Path) -> None:
    timings = {k: v for k, v in (state.get("timings") or {}).items() if k != "total"}
    if not timings:
        return
    labels = list(timings)
    vals = [timings[k] for k in labels]
    fig, ax = plt.subplots(figsize=(6.5, 3.0))
    ax.barh(labels, vals, color=PALETTE[0], height=0.55)
    total = sum(vals)
    for i, v in enumerate(vals):
        ax.text(v, i, f"  {v:,.0f}s ({v / total * 100:.1f}%)", va="center", fontsize=8)
    ax.set_xlabel("Wall-clock seconds")
    ax.set_xlim(0, max(vals) * 1.35)
    ax.grid(axis="y", visible=False)
    fig.tight_layout()
    _save(fig, out, "pipeline_timing")


