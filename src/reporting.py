def build_all(state: dict, results_dir: Path) -> None:
    results_dir.mkdir(parents=True, exist_ok=True)

    fig_training_curves(state, results_dir)
    fig_metrics_comparison(state, results_dir)
    fig_zkp_overhead(state, results_dir)
    fig_gas_comparison(state, results_dir)
    fig_pipeline_timing(state, results_dir)

    tables = {
        "table_datasets.tex": table_datasets(state),
        "table_link_prediction.tex": table_link_prediction(state),
        "table_soundness.tex": table_soundness(state),
        "table_onchain.tex": table_onchain(state),
    }
    for name, body in tables.items():
        (results_dir / name).write_text(body, encoding="utf-8")
        print(f"  -> {name}")

    m = MacroFile()

    # ---- environment ----
    env = state.get("environment", {})
    m.section("environment")
    m.add("envDevice", str(env.get("device", "cpu")).upper())
    m.add("envTorch", str(env.get("torch", "n/a")))
    m.add("envGPU", str(env.get("gpu", "CPU only")))
    m.add("envCommit", str(env.get("git_commit") or "n/a"))
    m.add("runProfile", str(state.get("profile", "n/a")))

    # ---- datasets ----
    ds = state.get("datasets") or {}
    m.section("datasets")
    m.add("numDatasets", str(len(ds)))
    for d in ds.values():
        key = macro_key(d["name"])
        m.add(f"{key}Entities", _fmt(d["entities"], thousands=True))
        m.add(f"{key}Relations", _fmt(d["relations"], thousands=True))
        m.add(f"{key}Train", _fmt(d["train"], thousands=True))
        m.add(f"{key}Valid", _fmt(d["valid"], thousands=True))
        m.add(f"{key}Test", _fmt(d["test"], thousands=True))

    # ---- link prediction ----
    lp = state.get("link_prediction") or {}
    m.section("link prediction")
    for ds_name, models in lp.items():
        key = macro_key(ds_name)
        for model, entry in models.items():
            mm = entry["metrics"]
            for metric, mac in [("MRR", "MRR"), ("Hits@1", "HitsOne"),
                                ("Hits@3", "HitsThree"), ("Hits@10", "HitsTen")]:
                m.add(f"{key}{model}{mac}", _fmt(mm[metric], 4))
        if models:
            best = max(models, key=lambda k: models[k]["metrics"]["MRR"])
            m.add(f"{key}BestModel", best)
            m.add(f"{key}BestMRR", _fmt(models[best]["metrics"]["MRR"], 4))

    # ---- ZKP ----
    z = state.get("zkp") or {}
    if z:
        m.section("zero-knowledge proofs")
        m.add("zkNumProofs", _fmt(z.get("num_proofs"), thousands=True))
        m.add("zkGenMs", _fmt(z.get("avg_gen_time", 0) * 1000))
        m.add("zkGenStdMs", _fmt(z.get("std_gen_time", 0) * 1000))
        m.add("zkVerifyMs", _fmt(z.get("avg_verify_time", 0) * 1000))
        m.add("zkVerifyStdMs", _fmt(z.get("std_verify_time", 0) * 1000))
        m.add("zkProofBytes", _fmt(z.get("avg_proof_size_bytes"), 0))
        m.add("zkAcceptRate", _fmt(z.get("verification_rate", 0) * 100, 1))
        m.add("zkTamperRate", _fmt(z.get("tamper_detection_rate", 0) * 100, 1))
        m.add("zkModel", str(z.get("model", "n/a")))
        m.add("zkDataset", str(z.get("dataset", "n/a")))
        m.add("zkFingerprint", str(z.get("model_fingerprint", ""))[:16])
        m.add("zkNumAdversaries", str(len(z.get("soundness") or {})))

    # ---- local EVM ----
    t = state.get("onchain_verifier_test")
    if t:
        m.section("in-memory EVM verification")
        m.add("evmVOneDeployGas", _fmt(t["v1"]["deploy_gas"], thousands=True))
        m.add("evmVTwoDeployGas", _fmt(t["v2"]["deploy_gas"], thousands=True))
        m.add("evmVOneLogGas", _fmt(t["v1"]["log_gas_steady_mean"], thousands=True))
        m.add("evmVTwoLogGas", _fmt(t["v2"]["log_gas_steady_mean"], thousands=True))
        m.add("evmVerifyOnlyGas", _fmt(t["v2"]["verify_gas_mean"], thousands=True))
        m.add("evmRegisterGas", _fmt(t["v2"].get("register_gas"), thousands=True))
        m.add("evmTrustlessDeltaGas", _fmt(t["cost_of_trustlessness_gas"], thousands=True))
        m.add("evmTrustlessDeltaPct", _fmt(t["cost_of_trustlessness_pct"], 1))
        m.add("evmNumAdversariesOnchain",
              str(len([k for k, v in (t.get("soundness") or {}).items()
                       if "inert" not in str(v)])))

    # ---- Sepolia ----
    s = state.get("sepolia") or {}
    if s.get("num_tx"):
        m.section("sepolia")
        m.add("sepoliaContract", str(s.get("contract_address", "")))
        m.add("sepoliaContractShort",
              f"{str(s.get('contract_address',''))[:6]}...{str(s.get('contract_address',''))[-4:]}")
        m.add("sepoliaVersion", str(s.get("contract_version", "v2")))
        m.add("sepoliaNumTx", _fmt(s["num_tx"], thousands=True))
        m.add("sepoliaFirstGas", _fmt(s.get("first_tx_gas"), thousands=True))
        m.add("sepoliaSteadyGas", _fmt(s.get("steady_state_avg_gas"), thousands=True))
        m.add("sepoliaSteadyStdGas", _fmt(s.get("steady_state_std_gas"), 0))
        m.add("sepoliaTotalGas", _fmt(s.get("total_gas_used"), thousands=True))
        m.add("sepoliaTotalCostETH", _fmt(s.get("total_cost_eth"), 5))
        m.add("sepoliaLatency", _fmt(s.get("median_latency_s"), 1))
        dep = s.get("deployment") or {}
        if dep:
            m.add("sepoliaDeployGas", _fmt(dep.get("deploy_gas_used"), thousands=True))
            m.add("sepoliaDeployCostETH", _fmt(dep.get("deploy_cost_eth"), 5))
            m.add("sepoliaDeployTx", str(dep.get("deploy_tx", "")))
        ctx = s.get("context") or {}
        vg = ctx.get("verify_only_gas_mean")
        if vg:
            m.add("sepoliaVerifyOnlyGas", _fmt(vg, thousands=True))
        reg = ctx.get("registration") or {}
        if reg.get("gas_used"):
            m.add("sepoliaRegisterGas", _fmt(reg["gas_used"], thousands=True))
        if reg.get("block_number"):
            m.add("sepoliaRegisterBlock", _fmt(reg["block_number"], thousands=True))
        if ctx.get("model_fingerprint"):
            m.add("sepoliaWeightDigest", str(ctx["model_fingerprint"])[:16])


    # ---- mainnet projections ----
    #
    # Derived from measured gas at stated prices; these are projections, not
    # measurements, and the paper labels them as such. Sepolia gas is
    # preferred when available because it reflects real consensus execution;
    # otherwise the in-memory EVM figure is used, which matches Sepolia
    # closely (both reproduce the same deployment gas exactly).
    steady_gas = None
    basis = None
    if s.get("steady_state_avg_gas"):
        steady_gas, basis = s["steady_state_avg_gas"], "sepolia"
    elif t:
        steady_gas, basis = t["v2"]["log_gas_steady_mean"], "in-memory EVM"
    if steady_gas:
        m.section(f"mainnet projections (basis: {basis}, $3000/ETH)")
        for gwei, label in [(30, "High"), (10, "Mid"), (5, "Low")]:
            m.add(f"mainnetRecordUSD{label}",
                  _fmt(steady_gas * gwei * 1e-9 * 3000, 2),
                  f"{gwei} gwei, projection from {basis}")

    # ---- timings ----
    timings = state.get("timings") or {}
    if timings:
        m.section("wall-clock timings")
        for k, v in timings.items():
            key = "".join(p.capitalize() for p in k.replace("-", "_").split("_"))
            m.add(f"time{key}", _fmt(v, 1))

        # The stage timers measure one invocation, so a model restored from a
        # checkpoint contributes nothing to timeTrain even though it was
        # trained. Quoting that in the paper would understate the cost of
        # reproducing this work. These macros sum the per-model times recorded
        # with the models themselves, so they describe the whole experiment
        # however many sittings it took.
        lp = state.get("link_prediction") or {}
        train_s = sum(e["history"]["total_time"]
                      for models in lp.values() for e in models.values())
        eval_s = sum(e["metrics"]["eval_time"]
                     for models in lp.values() for e in models.values())
        if train_s:
            other_s = sum(v for k, v in timings.items() if k != "train")
            m.add("timeTrainWork", _fmt(train_s, 1),
                  "summed over every model, checkpoint reuse excluded")
            m.add("timeEvalWork", _fmt(eval_s, 1))
            m.add("timeEndToEnd", _fmt(train_s + eval_s + other_s, 1))
            m.add("timeEndToEndMin", _fmt((train_s + eval_s + other_s) / 60, 1))
            m.add("pctCryptoOverhead",
                  _fmt(100.0 * other_s / (train_s + eval_s + other_s), 1))

    m.write(results_dir / "paper_macros.tex")
