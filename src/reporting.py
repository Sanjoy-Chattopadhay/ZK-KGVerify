def table_link_prediction(state: dict) -> str:
    lp = state.get("link_prediction") or {}
    rows = []
    for ds, models in lp.items():
        rows.append(r"\midrule")
        rows.append(rf"\multicolumn{{5}}{{l}}{{\emph{{{ds}}}}} \\")
        best = max(models, key=lambda m: models[m]["metrics"]["MRR"]) if models else None
        for model, entry in models.items():
            m = entry["metrics"]
            cells = [f"{m[k]:.4f}" for k in ("MRR", "Hits@1", "Hits@3", "Hits@10")]
            if model == best:
                cells = [rf"\textbf{{{c}}}" for c in cells]
                name = rf"\textbf{{{model}}}"
            else:
                name = model
            rows.append(f"{name} & " + " & ".join(cells) + r" \\")
    body = "\n".join(rows)
    return (
        "\\begin{tabular}{lcccc}\n\\toprule\n"
        "\\textbf{Model} & \\textbf{MRR} & \\textbf{Hits@1} & "
        "\\textbf{Hits@3} & \\textbf{Hits@10} \\\\\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n"
    )


def table_datasets(state: dict) -> str:
    ds = state.get("datasets") or {}
    rows = [
        f"{d['name']} & {d['entities']:,} & {d['relations']:,} & "
        f"{d['train']:,} & {d['valid']:,} & {d['test']:,} \\\\".replace(",", "{,}")
        for d in ds.values()
    ]
    return (
        "\\begin{tabular}{lccccc}\n\\toprule\n"
        "\\textbf{Dataset} & \\textbf{Entities} & \\textbf{Relations} & "
        "\\textbf{Train} & \\textbf{Valid} & \\textbf{Test} \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def table_soundness(state: dict) -> str:
    z = state.get("zkp") or {}
    s = z.get("soundness") or {}
    labels = {
        "A1_response_tamper": "A1: response scalar $s_v$ perturbed",
        "A2_prediction_swap": "A2: answered entity swapped after proving",
        "A3_score_inflation": "A3: reported confidence inflated",
        "A4_commitment_swap": "A4: commitment replaced with an unopenable one",
        "A5_offcurve_point": "A5: announcement forced off the curve",
        "A6_unregistered_model": "A6: honest proof for an unregistered model",
    }

    def label_for(key: str) -> str:
        """Never emit a raw key: underscores would break out of text mode."""
        return labels.get(key, key.replace("_", " "))

    rows = [
        f"{label_for(k)} & {v['trials']:,} & {v['rejected']:,} & "
        f"{v['rate']*100:.1f}\\% \\\\".replace(",", "{,}")
        for k, v in s.items()
    ]
    return (
        "\\begin{tabular}{lccc}\n\\toprule\n"
        "\\textbf{Adversary} & \\textbf{Trials} & \\textbf{Rejected} & "
        "\\textbf{Detection} \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )


def table_onchain(state: dict) -> str:
    """The paper's headline table: what chain-enforced verification costs.

    V1 stores whatever boolean the caller asserts; V2 re-derives the
    Fiat-Shamir challenge and checks the group equation inside the EVM,
    reverting if it fails. The interesting quantity is the difference.
    """
    t = state.get("onchain_verifier_test")
    if not t:
        return "% no on-chain verifier results in state\n"

    v1, v2 = t["v1"], t["v2"]

    def g(x) -> str:
        return f"{x:,.0f}".replace(",", "{,}") if x is not None else "--"

    delta = t.get("cost_of_trustlessness_gas")
    pct = t.get("cost_of_trustlessness_pct")

    rows = [
        f"Contract deployment & {g(v1['deploy_gas'])} & {g(v2['deploy_gas'])} \\\\",
        f"Model registration & -- & {g(v2.get('register_gas'))} \\\\",
        f"Proof verification (call only) & -- & {g(v2.get('verify_gas_mean'))} \\\\",
        "\\midrule",
        f"Record, first call & {g(v1['log_gas_first'])} & {g(v2['log_gas_first'])} \\\\",
        f"Record, steady state & {g(v1['log_gas_steady_mean'])} & "
        f"{g(v2['log_gas_steady_mean'])} \\\\",
    ]
    caption_row = (
        f"\\multicolumn{{3}}{{l}}{{\\footnotesize Cost of trustlessness: "
        f"$+{g(delta)}$ gas ({pct:+.2f}\\%) per record.}} \\\\"
        if delta is not None and pct is not None else ""
    )

    return (
        "\\begin{tabular}{lrr}\n\\toprule\n"
        "\\textbf{Operation} & \\textbf{V1 (unverified)} & "
        "\\textbf{V2 (chain-verified)} \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n"
        + (caption_row + "\n" if caption_row else "")
        + "\\end{tabular}\n"
    )


