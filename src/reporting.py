"""
Turn a completed run into the figures, tables, and macros the paper uses.

The important output is `results/paper_macros.tex`. Every quantity the
manuscript states is emitted there as a LaTeX macro, and the manuscript
cites the macro rather than a literal. A number can then only change by
re-running the experiment, which is what stopped the earlier drift where the
text quoted 30 on-chain records while the shipped log held 15.

`tools/check_paper_numbers.py` re-reads both files and fails if the .tex
contains a hard-coded figure that a macro should be carrying.
"""

