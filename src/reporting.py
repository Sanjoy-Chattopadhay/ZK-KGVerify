def _fmt(x: Optional[float], places: int = 2, thousands: bool = False) -> str:
    if x is None:
        return "n/a"
    if thousands:
        return f"{x:,.0f}".replace(",", "{,}")
    return f"{x:.{places}f}"


# Macros the manuscript references. Any that a run did not produce are still
# emitted, as a loud placeholder, so the document always compiles and a
# missing measurement is visible on the page instead of failing the build
# with an undefined-control-sequence error three hours into a deadline.
REQUIRED_MACROS = [
    # environment
    "envDevice", "envTorch", "envGPU", "envCommit", "runProfile",
    # zkp
    "zkNumProofs", "zkGenMs", "zkGenStdMs", "zkVerifyMs", "zkVerifyStdMs",
    "zkProofBytes", "zkAcceptRate", "zkTamperRate", "zkModel", "zkDataset",
    "zkFingerprint", "zkNumAdversaries",
    # local EVM
    "evmVOneDeployGas", "evmVTwoDeployGas", "evmVOneLogGas", "evmVTwoLogGas",
    "evmVerifyOnlyGas", "evmRegisterGas", "evmTrustlessDeltaGas",
    "evmTrustlessDeltaPct",
    # mainnet projections
    "mainnetRecordUSDHigh", "mainnetRecordUSDMid", "mainnetRecordUSDLow",
]

PLACEHOLDER = r"\textbf{[PENDING]}"

# LaTeX control sequences are letters only -- \FB15k237Entities parses as \FB
# followed by stray body text, which fails in the preamble with a confusing
# "Missing \begin{document}". Datasets therefore get short alphabetic aliases
# rather than having their names mangled into macro keys.
DATASET_ALIAS = {
    "FB15k-237": "FB",
    "WN18RR": "WN",
}


def macro_key(name: str) -> str:
    """Alphabetic-only identifier safe to use in a control sequence."""
    if name in DATASET_ALIAS:
        return DATASET_ALIAS[name]
    digits = str.maketrans(
        {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
         "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    )
    return "".join(ch for ch in name.translate(digits) if ch.isalpha())


class MacroFile:
    """Accumulates \\newcommand definitions for the manuscript."""

    def __init__(self) -> None:
        self.lines: list[str] = []
        self.seen: set[str] = set()

    def add(self, name: str, value: str, comment: str = "") -> None:
        if not name.isalpha():
            raise ValueError(
                f"macro name {name!r} is not purely alphabetic; LaTeX would "
                "truncate it at the first non-letter. Use macro_key()."
            )
        if name in self.seen:
            raise ValueError(f"duplicate macro {name}")
        self.seen.add(name)
        suffix = f"  % {comment}" if comment else ""
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}{suffix}")

    def section(self, title: str) -> None:
        self.lines.append("")
        self.lines.append(f"% ---- {title} ----")

    def fill_missing(self) -> list[str]:
        """Emit placeholders for required macros this run did not measure."""
        missing = [m for m in REQUIRED_MACROS if m not in self.seen]
        if missing:
            self.section("NOT MEASURED IN THIS RUN -- rerun the relevant stage")
            for name in missing:
                self.add(name, PLACEHOLDER, "no measurement available")
        return missing

    def write(self, path: Path) -> None:
        missing = self.fill_missing()
        header = [
            "% ==================================================================",
            "% AUTO-GENERATED by src/reporting.py -- do not edit by hand.",
            "% Regenerate with: python run_all.py --stages report",
            "%",
            "% Every experimental number in the manuscript is defined here and",
            "% referenced by macro, so the text cannot drift from results/.",
            "% ==================================================================",
            "",
        ]
        path.write_text("\n".join(header + self.lines) + "\n", encoding="utf-8")
        print(f"  -> {path.name} ({len(self.seen)} macros)")
        if missing:
            print(f"     WARNING: {len(missing)} macro(s) unmeasured, "
                  f"emitted as {PLACEHOLDER}:")
            for name in missing:
                print(f"       - \\{name}")


